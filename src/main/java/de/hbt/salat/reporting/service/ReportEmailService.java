package de.hbt.salat.reporting.service;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.MessageSource;
import org.springframework.stereotype.Service;
import de.hbt.salat.common.SalatProperties;
import de.hbt.salat.common.exception.ErrorCode;
import de.hbt.salat.common.exception.InvalidDataException;
import de.hbt.salat.common.mail.MailTemplates;
import de.hbt.salat.common.service.MailService;
import de.hbt.salat.common.service.MailService.EmailAttachment;
import de.hbt.salat.common.service.MailService.EmailRequest;
import de.hbt.salat.common.service.MailService.MailContact;
import de.hbt.salat.common.util.DateTimeUtils;
import de.hbt.salat.common.util.DateUtils;
import de.hbt.salat.reporting.domain.ReportDefinition;
import de.hbt.salat.reporting.domain.ReportParameter;
import de.hbt.salat.reporting.domain.ReportResult;

@Slf4j
@Service
@RequiredArgsConstructor
public class ReportEmailService {

  private static final Locale LOCALE = Locale.GERMAN;

  private final ExcelExportService excelExportService;
  private final ReportService reportService;
  private final MailService mailService;
  private final MailTemplates mailTemplates;
  private final MessageSource messageSource;
  private final SalatProperties salatProperties;

  @Value("${salat.reporting.email.from:noreply@salat.local}")
  private String fromAddress;

  @Value("${salat.reporting.email.enabled:true}")
  private boolean emailEnabled;

  public record  SendResult(int rowCount, boolean suppressed, boolean error, ReportResult.ErrorInfo errorInfo) {}

  public SendResult sendReportEmail(Long reportDefinitionId, List<ReportParameter> parameters, String[] recipients, boolean suppressEmptyResults) {
    try {
      if (!emailEnabled) {
        log.info("Email sending is disabled. Skipping report email for report ID: {}", reportDefinitionId);
        return new SendResult(0, true, false, null);
      }

      log.info("Generating report {} with parameters: {}", reportDefinitionId, parameters);
      ReportDefinition rd = reportService.getReportDefinition(reportDefinitionId);
      if(rd == null) throw new InvalidDataException(ErrorCode.XX_DATA_MISSING, "No report definition found for ID: " + reportDefinitionId);
      ReportResult reportResult = reportService.execute(reportDefinitionId, parameters);

      if(reportResult.isError()) {
        return new SendResult(0, false, true, reportResult.getErrorInfo());
      }

      int rowCount = reportResult.getRows().size();

      if(suppressEmptyResults && reportResult.getRows().isEmpty()) {
        log.info("Report id={}, name={} returned no rows. Skipping email (suppressEmptyResults=true).", reportDefinitionId, rd.getName());
        return new SendResult(0, true, false, null);
      }

      byte[] excelBytes = excelExportService.exportToExcel(reportResult);

      // group and title (#1523), as the name read with its prefix before
      var reportName = reportService.getGroupOf(rd).qualify(rd.getName());
      String fileName = createFileName(reportName);
      var facts = facts(reportResult, parameters);

      MailContact from = new MailContact("Salat", fromAddress);
      MailContact primaryRecipient = new MailContact("", recipients[0].trim());

      List<MailContact> additionalRecipients = new ArrayList<>();
      for (int i = 1; i < recipients.length; i++) {
        additionalRecipients.add(new MailContact("", recipients[i].trim()));
      }

      EmailRequest emailRequest = EmailRequest.builder()
          .subject(text("main.mail.report.subject", reportName))
          .message(buildEmailBody(reportName, facts))
          .htmlMessage(mailTemplates.render("mail/report", LOCALE, Map.of(
              "reportName", reportName, "facts", facts, "fileName", fileName, "jobsUrl", jobsUrl())))
          .from(from)
          .to(primaryRecipient)
          .additionalRecipients(additionalRecipients)
          .attachment(new EmailAttachment(
              fileName,
              excelBytes,
              "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
          ))
          .appendAutoGeneratedFooter(false)
          .build();

      mailService.sendEmail(emailRequest);
      log.info("Report email sent successfully to {} recipients for report: {}", recipients.length, rd.getName());
      return new SendResult(reportResult.getRows().size(), false, false, null);

    } catch (Exception e) {
      log.error("Failed to send report email for report ID: {}", reportDefinitionId, e);
      throw new RuntimeException("Failed to send report email", e);
    }
  }

  /**
   * The text part (#1505): what the HTML part says, in the du-form of the whole application. Reports go
   * to addresses rather than to persons, so they come in German.
   */
  private String buildEmailBody(String reportName, List<Map.Entry<String, String>> facts) {
    StringBuilder body = new StringBuilder();
    body.append(text("main.mail.greeting")).append("\n\n");
    body.append(text("main.mail.report.intro", reportName)).append("\n\n");
    facts.forEach(fact -> body.append("- ").append(fact.getKey()).append(": ").append(fact.getValue()).append("\n"));
    body.append("\n").append(text("main.mail.report.attachment")).append("\n\n");
    body.append("__________________________\n\n");
    body.append(text("main.mail.footer.automatic")).append("\n");
    body.append(text("main.mail.footer.report")).append("\n").append(jobsUrl());
    return body.toString();
  }

  /** The parameters, the number of rows and when the report was made, in the order the mail lists them. */
  private List<Map.Entry<String, String>> facts(ReportResult reportResult, List<ReportParameter> parameters) {
    var facts = new ArrayList<Map.Entry<String, String>>();
    parameters.forEach(parameter -> facts.add(Map.entry(parameter.getName(), String.valueOf(parameter.getValue()))));
    facts.add(Map.entry(text("main.mail.report.rows"), String.valueOf(reportResult.getRows().size())));
    facts.add(Map.entry(text("main.mail.report.generated"),
        DateUtils.formatDateTime(DateTimeUtils.now(), "dd.MM.yyyy HH:mm")));
    return facts;
  }

  private String jobsUrl() {
    return salatProperties.absoluteUrl("/reporting/jobs");
  }

  private String text(String key, Object... arguments) {
    return messageSource.getMessage(key, arguments, LOCALE);
  }

  private String createFileName(String reportName) {
    var fileName = "report-" + reportName +
                   "-erzeugt-" + DateUtils.formatDateTime(DateTimeUtils.now(), "dd-MM-yy-HHmm") +
                   ".xlsx";
    return fileName.replaceAll("[^a-zA-Z0-9-_.]", "_");
  }

}
