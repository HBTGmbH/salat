package de.hbt.salat.notification.service;

import static de.hbt.salat.common.exception.ErrorCode.XX_MAIL_NOT_SENT;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.doThrow;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;

import de.hbt.salat.common.SalatProperties;
import de.hbt.salat.common.exception.BusinessRuleException;
import de.hbt.salat.common.exception.ErrorCodeException;
import de.hbt.salat.common.exception.ServiceFeedbackMessage;
import de.hbt.salat.common.notification.NotificationRecipient;
import de.hbt.salat.common.service.MailService;
import de.hbt.salat.common.service.MailService.EmailRequest;
import de.hbt.salat.common.service.MailService.MailContact;
import de.hbt.salat.notification.domain.NotificationMessage;
import java.util.List;
import java.util.Locale;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayNameGeneration;
import org.junit.jupiter.api.DisplayNameGenerator.ReplaceUnderscores;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.springframework.context.support.ResourceBundleMessageSource;
import org.springframework.transaction.support.TransactionSynchronization;
import org.springframework.transaction.support.TransactionSynchronizationManager;

/**
 * The mail of a notification (#828), with the texts of the bundles: in the language of its
 * recipient, after the commit where it may be switched off, at once and with a reported failure
 * where it is the point of the action.
 */
@DisplayNameGeneration(ReplaceUnderscores.class)
class NotificationMailerTest {

  private static final NotificationMessage RELEASED = NotificationMessage.builder()
      .titleKey("main.release.notification.released.title").titleParams(List.of("Person A"))
      .descriptionKey("main.release.notification.released.description").descriptionParams(List.of("Person A", "30.09.2026"))
      .actionUrl("/acceptance/accept/review?contractId=7&until=2026-09")
      .build();

  private final MailService mailService = mock(MailService.class);
  private NotificationMailer mailer;

  @BeforeEach
  void setUp() {
    var messageSource = new ResourceBundleMessageSource();
    messageSource.setBasename("de/hbt/salat/web/MessageResources");
    messageSource.setDefaultEncoding("UTF-8");
    messageSource.setFallbackToSystemLocale(false);
    var properties = new SalatProperties();
    properties.setUrl("https://salat.example.org");
    properties.getNotifications().setEmailFrom("noreply@example.org");
    mailer = new NotificationMailer(mailService, messageSource, properties);
  }

  @AfterEach
  void tearDown() {
    if (TransactionSynchronizationManager.isSynchronizationActive()) {
      TransactionSynchronizationManager.clearSynchronization();
    }
  }

  @Test
  void writes_title_greeting_description_and_link_in_german() {
    mailer.mailAfterCommit(recipient(Locale.GERMAN), RELEASED);

    var mail = sent();
    assertThat(mail.getSubject()).isEqualTo("SALAT: Person A hat Buchungen freigegeben");
    assertThat(mail.getMessage()).isEqualTo("""
        Hallo Person B,

        Person A hat die Buchungen bis 30.09.2026 freigegeben. Bitte nimm sie ab.

        In Salat öffnen: https://salat.example.org/acceptance/accept/review?contractId=7&until=2026-09

        __________________________

        (Dies ist eine automatisch erzeugte E-Mail.)""");
    assertThat(mail.getTo()).isEqualTo(new MailContact("Person B", "person.b@example.org"));
    assertThat(mail.getFrom()).isEqualTo(new MailContact("Salat", "noreply@example.org"));
    assertThat(mail.isAppendAutoGeneratedFooter()).isFalse();
  }

  @Test
  void writes_in_english_for_whoever_chose_english() {
    mailer.mailAfterCommit(recipient(Locale.ENGLISH), RELEASED);

    var mail = sent();
    assertThat(mail.getSubject()).isEqualTo("SALAT: Person A released bookings");
    assertThat(mail.getMessage()).startsWith("Hello Person B,").contains("Please accept them.")
        .endsWith("(This is an automatically generated email.)");
  }

  @Test
  void comes_from_the_person_who_caused_it() {
    var sender = new MailContact("Person A", "person.a@example.org");

    mailer.mailAfterCommit(recipient(Locale.GERMAN), withSender(sender));

    assertThat(sent().getFrom()).isEqualTo(sender);
  }

  /** The budget alert names the order in the mail, which the bell leaves out. */
  @Test
  void says_more_than_the_bell_where_the_notification_has_a_text_of_its_own_for_the_mail() {
    mailer.mailAfterCommit(recipient(Locale.GERMAN), released()
        .mailDescriptionKey("main.budget.alert.email.body").mailDescriptionParams(List.of("Plan", "ABC-12", "90,0", "80"))
        .build());

    assertThat(sent().getMessage()).contains(
        "Die Budgetauslastung für Plan (Auftrag: ABC-12) beträgt 90,0 % und überschreitet den Schwellenwert von 80 %.");
  }

  @Test
  void within_a_transaction_waits_for_the_commit() {
    TransactionSynchronizationManager.initSynchronization();

    mailer.mailAfterCommit(recipient(Locale.GERMAN), RELEASED);

    verify(mailService, never()).sendEmail(any(EmailRequest.class));
    TransactionSynchronizationManager.getSynchronizations().forEach(TransactionSynchronization::afterCommit);
    verify(mailService).sendEmail(any(EmailRequest.class));
  }

  @Test
  void a_failure_after_the_commit_fails_nothing() {
    doThrow(new RuntimeException("mail server down")).when(mailService).sendEmail(any(EmailRequest.class));

    mailer.mailAfterCommit(recipient(Locale.GERMAN), RELEASED);

    verify(mailService).sendEmail(any(EmailRequest.class));
  }

  @Test
  void without_an_address_nothing_is_sent() {
    mailer.mailAfterCommit(new NotificationRecipient(1L, "", null, Locale.GERMAN, true, true), RELEASED);

    verify(mailService, never()).sendEmail(any(EmailRequest.class));
  }

  @Test
  void a_mandatory_mail_that_fails_is_reported_with_the_recipient() {
    doThrow(new RuntimeException("mail server down")).when(mailService).sendEmail(any(EmailRequest.class));

    assertThatThrownBy(() -> mailer.mailNow(recipient(Locale.GERMAN), RELEASED))
        .isInstanceOf(BusinessRuleException.class)
        .extracting(e -> ((ErrorCodeException) e).getMessages().getFirst())
        .extracting(ServiceFeedbackMessage::getErrorCode, ServiceFeedbackMessage::getArguments)
        .containsExactly(XX_MAIL_NOT_SENT, List.of("Person B"));
  }

  @Test
  void a_mandatory_mail_without_an_address_is_reported() {
    assertThatThrownBy(() -> mailer.mailNow(new NotificationRecipient(1L, "Person B", " ", Locale.GERMAN, true, true), RELEASED))
        .isInstanceOf(BusinessRuleException.class);
    verify(mailService, never()).sendEmail(any(EmailRequest.class));
  }

  private static NotificationRecipient recipient(Locale locale) {
    return new NotificationRecipient(1L, "Person B", "person.b@example.org", locale, true, true);
  }

  private static NotificationMessage withSender(MailContact sender) {
    return released().sender(sender).build();
  }

  private static NotificationMessage.NotificationMessageBuilder released() {
    return NotificationMessage.builder()
        .titleKey(RELEASED.titleKey()).titleParams(RELEASED.titleParams())
        .descriptionKey(RELEASED.descriptionKey()).descriptionParams(RELEASED.descriptionParams())
        .actionUrl(RELEASED.actionUrl());
  }

  private EmailRequest sent() {
    var request = ArgumentCaptor.forClass(EmailRequest.class);
    verify(mailService).sendEmail(request.capture());
    return request.getValue();
  }
}
